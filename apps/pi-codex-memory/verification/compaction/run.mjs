import { mkdir, mkdtemp, readFile, access } from "node:fs/promises";
import { createWriteStream } from "node:fs";
import { spawn } from "node:child_process";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LENGTHS, MODELS, makeFixture, sha256 } from "./fixtures.mjs";
import { privateJSON } from "../live/runtime.mjs";

const root = resolve(process.argv[2]), action = process.argv[3] ?? "prepare";
await mkdir(root, { recursive: true, mode: 0o700 });
const packageRoot = fileURLToPath(new URL("../../", import.meta.url));
const repository = resolve(packageRoot, "../..");
if (action === "prepare") {
    try { await access(join(root, "manifest.json")); throw new Error("Existing verification manifest must not be overwritten."); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    const providerPaths = JSON.parse(await readFile(join(repository, ".reports/codex-memory/live-benchmark/provider-paths.json"), "utf8"));
    const workspaces = {};
    for (const length of LENGTHS) {
        await privateJSON(join(root, `${length.key}-fixture.json`), makeFixture(length));
        for (const model of MODELS) workspaces[`${model.key}-${length.key}`] = await mkdtemp("/tmp/pi-memory-compaction-");
    }
    const fingerprints = {};
    for (const name of ["index", "runtime", "sources", "pipeline", "retrieval", "store", "config", "safety", "failure", "commands"])
        fingerprints[`dist/${name}.js`] = sha256(await readFile(join(packageRoot, `dist/${name}.js`)));
    const manifest = { createdAt: new Date().toISOString(), maximumRequests: 240, models: MODELS, lengths: LENGTHS,
        providerPaths: { "claude-bridge": providerPaths["claude-bridge"] }, workspaces, fingerprints,
        caveats: ["Synthetic facts and reference data; every dialogue assistant response and compaction summary is generated by a real model.",
            "Short/medium compaction uses a reduced keepRecentTokens setting. Long compaction uses an explicitly reduced automatic threshold, not a full default provider context window.",
            "Default 256 KiB input and 4096 output-token failures are preserved before an applicable 512 KiB or 8192-token retry.",
            "Host request cap is not a billing ceiling or provider-internal HTTP retry count."] };
    await privateJSON(join(root, "manifest.json"), manifest);
    console.log(JSON.stringify({ root, maximumRequests: manifest.maximumRequests, lengths: LENGTHS }));
} else {
    const mode = process.argv[4];
    if (mode && mode !== "recall-recheck") throw new Error("Unknown verification mode.");
    const suffix = mode ? "-recall-recheck" : "";
    const length = LENGTHS.find(item => item.key === action);
    if (!length) throw new Error("Choose prepare, short, medium, or long.");
    const worker = fileURLToPath(new URL("worker.mjs", import.meta.url));
    for (const model of MODELS) {
        try { await access(join(root, `${model.key}-${length.key}${suffix}.log`)); throw new Error("Prior case logs must not be overwritten."); }
        catch (error) { if (error.code !== "ENOENT") throw error; }
    }
    const children = [];
    for (const signal of ["SIGINT", "SIGTERM"]) process.once(signal, () => { for (const child of children) child.kill("SIGTERM"); });
    const jobs = MODELS.map(model => new Promise((resolveJob, reject) => {
        const log = createWriteStream(join(root, `${model.key}-${length.key}${suffix}.log`), { flags: "wx", mode: 0o600 });
        const child = spawn(process.execPath, [worker, root, model.key, length.key, ...(mode ? [mode] : [])], {
            cwd: repository, env: { ...process.env, PI_MEMORY_BUDGET: join(root, "model-budget.sqlite") }, stdio: ["ignore", "pipe", "pipe"] });
        children.push(child);
        child.stdout.pipe(log, { end: false }); child.stderr.pipe(log, { end: false });
        child.on("error", error => { log.end(); reject(error); });
        child.on("exit", (code, signal) => { log.end(); resolveJob({ key: model.key, length: length.key, code, signal }); });
    }));
    const results = await Promise.allSettled(jobs);
    await privateJSON(join(root, `${length.key}${suffix}-execution.json`), results);
    console.log(JSON.stringify(results));
    if (results.some(result => result.status !== "fulfilled" || result.value.code !== 0)) process.exitCode = 1;
}
