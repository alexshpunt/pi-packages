// Regenerate src/pii/data/*.ts from the byte-for-byte JSON copies in the
// package's vendor/presidio-pii, which the formatter leaves untouched.
// Pi loads extensions through jiti, so the data ships as JavaScript string
// constants instead of JSON imports or runtime file reads.
import { readFile, writeFile } from "node:fs/promises";

const packageRoot = new URL("../", import.meta.url);
const vendorDirectory = new URL("../vendor/presidio-pii/", import.meta.url);
const sources = [
    ["catalog.json", "catalog.ts", "CATALOG_JSON"],
    ["iban_formats.json", "iban-formats.ts", "IBAN_FORMATS_JSON"],
    ["validation_data.json", "validation-data.ts", "VALIDATION_DATA_JSON"],
];

/** A string literal in the quote style the repository formatter keeps: fewer escapes wins. */
function stringLiteral(text) {
    const quoted = JSON.stringify(text);
    const doubleQuotes = text.split('"').length - 1;
    const singleQuotes = text.split("'").length - 1;
    if (doubleQuotes <= singleQuotes) return quoted;
    // In JSON string text every `"` is escaped and every `\"` is such an escape.
    return `'${quoted.slice(1, -1).replaceAll('\\"', '"').replaceAll("'", "\\'")}'`;
}

for (const [source, target, constant] of sources) {
    const text = await readFile(new URL(source, vendorDirectory), "utf8");
    let output = `// Generated by scripts/generate-pii-data.mjs from vendor/presidio-pii/${source}. Do not edit.\n`;
    if (source === "catalog.json") {
        const names = JSON.parse(text).map((entry) => entry.entity);
        output += `export const PII_ENTITY_NAMES: readonly string[] = Object.freeze([\n${names.map((name) => `    ${JSON.stringify(name)},\n`).join("")}]);\n`;
    }
    output += `export const ${constant} =\n    ${stringLiteral(text)};\n`;
    await writeFile(new URL(`src/pii/data/${target}`, packageRoot), output);
}
